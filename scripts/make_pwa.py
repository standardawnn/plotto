#!/usr/bin/env python3
"""Make the Plotto prototype installable (home-screen app) in one command.

Run from the project root:  python3 scripts/make_pwa.py

What it does (idempotent, safe to re-run):
  1. Generates app icons (192, 512, maskable 512, Apple touch 180) from public/brand/peek-character.png.
  2. Writes public/manifest.webmanifest (standalone app, starts at /mobile.html).
  3. Writes public/sw.js: a network-first service worker. It never serves stale HTML
     when the network works, which avoids white screens after an update.
  4. Injects the manifest, Apple meta tags and SW registration into mobile.html and dist/mobile.html.
  5. Copies manifest, icons and sw.js into dist/.
"""
import json
import os
import shutil
import time
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

BG_TOP = (37, 64, 199)      # #2540c7 (header gradient top)
BG_BOTTOM = (141, 160, 255)  # #8da0ff (header gradient bottom)
THEME = "#f4f7fd"
MARKER = "<!-- plotto-pwa -->"


def gradient(size):
    img = Image.new("RGB", (size, size), BG_TOP)
    draw = ImageDraw.Draw(img)
    for y in range(size):
        t = y / max(1, size - 1)
        color = tuple(int(BG_TOP[i] + (BG_BOTTOM[i] - BG_TOP[i]) * t) for i in range(3))
        draw.line([(0, y), (size, y)], fill=color)
    return img


def make_icon(size, path, safe=1.0):
    """safe < 1 shrinks the mark, for maskable icons (keep inside the 80% safe zone)."""
    base = gradient(size).convert("RGBA")
    mark = Image.open("public/brand/peek-character.png").convert("RGBA")
    target = int(size * 0.62 * safe)
    scale = target / max(mark.size)
    mark = mark.resize((max(1, int(mark.width * scale)), max(1, int(mark.height * scale))), Image.LANCZOS)
    base.alpha_composite(mark, ((size - mark.width) // 2, (size - mark.height) // 2))
    base.convert("RGB").save(path, "PNG", optimize=True)
    print("icon", path, size)


def write_icons():
    os.makedirs("public/icons", exist_ok=True)
    make_icon(192, "public/icons/icon-192.png")
    make_icon(512, "public/icons/icon-512.png")
    make_icon(512, "public/icons/icon-maskable-512.png", safe=0.8)
    make_icon(180, "public/icons/apple-touch-icon.png")


def write_manifest():
    manifest = {
        "name": "Plotto",
        "short_name": "Plotto",
        "id": "/mobile.html",
        "start_url": "/mobile.html",
        "scope": "/",
        "display": "standalone",
        "orientation": "portrait",
        "background_color": THEME,
        "theme_color": THEME,
        "icons": [
            {"src": "/icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "/icons/icon-512.png", "sizes": "512x512", "type": "image/png"},
            {"src": "/icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
        ],
    }
    with open("public/manifest.webmanifest", "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("manifest written")


SW_TEMPLATE = """// Generated by scripts/make_pwa.py. Network-first: fresh files whenever online,
// cached copies only when offline. Never caches error responses.
const CACHE = 'plotto-__VERSION__';
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(key => key !== CACHE).map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    try {
      const response = await fetch(request);
      if (response.ok && response.type === 'basic') {
        const copy = response.clone();
        caches.open(CACHE).then(cache => cache.put(request, copy)).catch(() => {});
      }
      return response;
    } catch (error) {
      const cached = await caches.match(request);
      if (cached) return cached;
      if (request.mode === 'navigate') {
        const shell = await caches.match('/mobile.html');
        if (shell) return shell;
      }
      throw error;
    }
  })());
});
"""


def write_sw():
    version = str(int(time.time()))
    with open("public/sw.js", "w", encoding="utf-8") as f:
        f.write(SW_TEMPLATE.replace("__VERSION__", version))
    print("sw.js written, version", version)


HEAD_SNIPPET = (
    MARKER
    + '<link rel="manifest" href="/manifest.webmanifest"/>'
    + '<link rel="apple-touch-icon" href="/icons/apple-touch-icon.png"/>'
    + '<meta name="apple-mobile-web-app-capable" content="yes"/>'
    + '<meta name="apple-mobile-web-app-status-bar-style" content="default"/>'
    + '<meta name="apple-mobile-web-app-title" content="Plotto"/>'
    + '<script>if("serviceWorker" in navigator){addEventListener("load",function(){navigator.serviceWorker.register("/sw.js").catch(function(){})})}</script>'
    + MARKER
)


def inject(path):
    if not os.path.exists(path):
        print("skip (missing)", path)
        return
    html = open(path, encoding="utf-8").read()
    if MARKER in html:
        start = html.index(MARKER)
        end = html.index(MARKER, start + len(MARKER)) + len(MARKER)
        html = html[:start] + html[end:]
    html = html.replace("</head>", HEAD_SNIPPET + "</head>", 1)
    open(path, "w", encoding="utf-8").write(html)
    print("injected", path)


def copy_to_dist():
    if not os.path.isdir("dist"):
        return
    os.makedirs("dist/icons", exist_ok=True)
    for name in ["icon-192.png", "icon-512.png", "icon-maskable-512.png", "apple-touch-icon.png"]:
        shutil.copy(os.path.join("public/icons", name), os.path.join("dist/icons", name))
    for name in ["manifest.webmanifest", "sw.js"]:
        shutil.copy(os.path.join("public", name), os.path.join("dist", name))
    print("copied to dist")


if __name__ == "__main__":
    write_icons()
    write_manifest()
    write_sw()
    inject("mobile.html")
    inject("dist/mobile.html")
    copy_to_dist()
    print("done")
